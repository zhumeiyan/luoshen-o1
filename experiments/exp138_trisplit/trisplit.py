    flips.append(("输液16/16存活", "L1:100%存活=最健康", "L3:能力归零=镜像态", True))
    # 高温fg最高：L1=最强 / L3=尺度泄漏
    flips.append(("高温fg 0.338", "L1:数值最高=最强", "L3:温度尺度非能力", True))
