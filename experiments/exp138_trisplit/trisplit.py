    # ---- 2. 跨层误判矩阵 ----
    print("\n" + "=" * 62)
    print("跨层误判矩阵：用 X 层的尺子量 Y 层的读数")
    print("=" * 62)
    cnt = {}
    for ruler, target, wrong, truth in MISREAD:
        cnt[ruler] = cnt.get(ruler, 0) + 1
        print(f"\n[用 {ruler} 尺] {target}")
        print(f"  误判  : {wrong}")
        print(f"  真相  : {truth}")

    # ---- 3. H1/H2 检验 ----
    print("\n" + "=" * 62)
    print("假设检验")
    print("=" * 62)

    # H1：同一读数在不同层判据下方向翻转
    flips = []
    # fg=0：L1看=0%效率(废品) / L3看=依赖负熵(生命定义)
