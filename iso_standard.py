    print(f"  BT.2020 {tri_area(bt2020):.4f}  覆盖自然 {tri_area(bt2020)/NAT*100:.1f}%")
    print(f"  BT.2020 是 sRGB 的 {tri_area(bt2020)/tri_area(srgb):.2f} 倍")

