    print("\n=== 五、色域覆盖（ITU-R 三原色 vs 自然）===")
    # 上一轮算过：自然马蹄形 0.3155，sRGB 0.1121 = 35.5%
    def tri_area(p):
        (x1,y1),(x2,y2),(x3,y3)=p
        return 0.5*abs(x1*(y2-y3)+x2*(y3-y1)+x3*(y1-y2))
    srgb=[(0.64,0.33),(0.30,0.60),(0.15,0.06)]
